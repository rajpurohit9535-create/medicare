/**
 * Creates today's instances from the demo tasks
 */
export function getDemoTodayInstances(): TaskInstanceItem[] {
  const todayStr = new Date().toISOString().split("T")[0];

  return INITIAL_DEMO_TASKS.map((task) => {
    return {
      id: `instance-${task.id}`,
      task_id: task.id,
      patient_id: task.patient_id,
      scheduled_for: `${todayStr}T${task.time_of_day}:00.000Z`,
      status: "pending",
      snoozed_until: null,
      snooze_count: 0,
      completed_at: null,
      tasks: task,
    };
  });
}

